// Branded domain identifiers. Every id erases to a string on the wire but the
// brand keeps call sites honest: a TaskId cannot be handed to a function that
// expects a JobId, which is the failure mode a plain `type TaskId = string`
// silently allows.

interface IdBrandMap {
  task: "task";
  job: "job";
  mission: "mission";
  run: "run";
}

export type IdKind = keyof IdBrandMap;
export type IdOf<K extends IdKind> = string & { readonly __idBrand: IdBrandMap[K] };

export type TaskId = IdOf<"task">;
export type JobId = IdOf<"job">;
export type MissionId = IdOf<"mission">;
export type AgentRunId = IdOf<"run">;

export type AnyId = TaskId | JobId | MissionId | AgentRunId;

// The body is generated by the caller (a database sequence, a nanoid, an uuid);
// the contract only guarantees a prefix that names the kind and a character set
// that is safe in URLs, filenames, and shell-quoted arguments.
const ID_BODY = /^[A-Za-z0-9_-]{6,128}$/;
const ID_FULL = /^(task|job|mission|run)_[A-Za-z0-9_-]{6,128}$/;

export function idPrefix(kind: IdKind): string {
  return `${kind}_`;
}

/** Build an id from an already-generated body. Throws when the body is unsafe. */
export function makeId<K extends IdKind>(kind: K, body: string): IdOf<K> {
  if (!ID_BODY.test(body)) {
    throw new TypeError(
      `Invalid ${kind} id body: expected 6-128 characters of [A-Za-z0-9_-], got ${JSON.stringify(body)}`,
    );
  }
  return `${kind}_${body}` as IdOf<K>;
}

/** Read an id that came from an untrusted boundary. Returns null instead of throwing. */
export function parseId<K extends IdKind>(kind: K, raw: unknown): IdOf<K> | null {
  if (typeof raw !== "string") return null;
  const prefix = idPrefix(kind);
  if (!raw.startsWith(prefix)) return null;
  return ID_FULL.test(raw) ? (raw as IdOf<K>) : null;
}

export function isId<K extends IdKind>(kind: K, raw: unknown): raw is IdOf<K> {
  return parseId(kind, raw) !== null;
}

/** Which kind a fully-formed id belongs to, or null when it is not a domain id. */
export function idKindOf(id: unknown): IdKind | null {
  if (typeof id !== "string") return null;
  const match = ID_FULL.exec(id);
  return match ? (match[1] as IdKind) : null;
}

/** Strip the brand for serialisation. Ids are already plain strings at runtime. */
export function idValue(id: AnyId): string {
  return id as string;
}

export const makeTaskId = (body: string): TaskId => makeId("task", body);
export const parseTaskId = (raw: unknown): TaskId | null => parseId("task", raw);
export const isTaskId = (raw: unknown): raw is TaskId => isId("task", raw);

export const makeJobId = (body: string): JobId => makeId("job", body);
export const parseJobId = (raw: unknown): JobId | null => parseId("job", raw);
export const isJobId = (raw: unknown): raw is JobId => isId("job", raw);

export const makeMissionId = (body: string): MissionId => makeId("mission", body);
export const parseMissionId = (raw: unknown): MissionId | null => parseId("mission", raw);
export const isMissionId = (raw: unknown): raw is MissionId => isId("mission", raw);

export const makeAgentRunId = (body: string): AgentRunId => makeId("run", body);
export const parseAgentRunId = (raw: unknown): AgentRunId | null => parseId("run", raw);
export const isAgentRunId = (raw: unknown): raw is AgentRunId => isId("run", raw);
